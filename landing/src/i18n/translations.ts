export type Lang = keyof typeof translations;
export type TranslationKey = keyof (typeof translations)[typeof defaultLang];

export function useTranslations(lang: Lang) {
  type DefaultDict = (typeof translations)[typeof defaultLang];
  const dict = translations[lang] as DefaultDict;

  return function t(key: TranslationKey) {
    return dict[key] ?? translations[defaultLang][key];
  };
}
